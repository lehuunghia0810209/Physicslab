const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async function checkExperiments(browser, base, out) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'vi-VN' });
  const page = await context.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  const snapshot = () => page.evaluate(()=>JSON.parse(localStorage.getItem('physicslab.experiments.v1')));
  const download = async (selector,name) => {
    const waiting=page.waitForEvent('download');await page.locator(selector).click();const file=await waiting;
    const target=path.join(out,name);await file.saveAs(target);return fs.readFileSync(target,'utf8');
  };
  try {
    await page.goto(`${base}/#/simulation/newton`);await page.locator('[data-run-name]').waitFor();
    await page.locator('#friction').fill('0');await page.locator('#force').fill('20');
    await page.locator('[data-run-name]').fill('Newton • đối chứng');await page.locator('[data-run-name]').dispatchEvent('change');
    await page.locator('.experiment-notebook>summary').click();
    await page.locator('[data-notebook-field="hypothesis"]').fill('Vận tốc tăng theo thời gian khi hợp lực không đổi.');
    await page.locator('[data-measure-capture]').click();await page.locator('#scrubber').fill('500');
    const expected=await page.evaluate(()=>window.PhysicsLabApp.context().simulation.measurements);
    await page.locator('[data-measure-capture]').click();
    assert.equal(await page.locator('[data-measure-body] tr').count(),2);
    await page.locator('[data-measure-select="0"]').uncheck();
    await page.locator('[data-notebook-field="conclusion"]').fill('Hai mẫu phù hợp a = 4 m/s².');
    await page.locator('[data-run-save]').click();
    let data=await snapshot();assert.equal(data.runs.length,1);assert.equal(data.runs[0].rows[1].velocity,expected.velocity);
    assert.deepEqual(data.runs[0].selected,[1]);assert.equal(data.runs[0].parameters.force,20);
    const id=data.runs[0].id;
    await page.reload();await page.locator('[data-run-name]').waitFor();
    assert.equal(await page.locator('[data-run-name]').inputValue(),'Newton • đối chứng');
    assert.equal(await page.locator('[data-measure-body] tr').count(),2);
    await page.locator('.experiment-notebook>summary').click();
    assert.equal(await page.locator('[data-notebook-field="conclusion"]').inputValue(),'Hai mẫu phù hợp a = 4 m/s².');
    assert.equal(await page.locator('[data-notebook-table] tr').count(),1);
    const report=JSON.parse(await download('[data-notebook-export]','studio-notebook.json'));
    assert.equal(report.evidence.rows.length,1);assert.equal(report.evidence.rows[0].velocity,expected.velocity);
    assert.equal(report.evidence.parameters.force,20);
    const csv=await download('[data-measure-export]','studio-newton.csv');assert.match(csv,/t_s,x_m,v_m_s/);
    assert.ok(csv.includes(expected.velocity.toFixed(6)));
    await page.locator('#force').fill('30');await page.locator('[data-measure-capture]').click();
    assert.match(await page.locator('[data-measure-status]').textContent(),/Thiết lập đã thay đổi/);
    assert.equal((await snapshot()).drafts.newton.rows.length,2,'changed setup cannot contaminate previous measurements');
    await page.locator('[data-run-new]').click();
    assert.equal((await snapshot()).runs.length,1);assert.equal((await snapshot()).drafts.newton.rows.length,0);
    assert.equal(await page.locator('#scrubber').inputValue(),'0');
    await page.locator('[data-measure-capture]').click();await page.locator('#scrubber').fill('500');
    await page.locator('[data-measure-capture]').click();await page.locator('[data-run-save]').click();
    assert.equal((await snapshot()).runs.length,2);
    page.once('dialog',dialog=>dialog.dismiss());await page.locator('[data-measure-clear]').click();
    assert.equal((await snapshot()).drafts.newton.rows.length,2,'cancelled clear must preserve data');
    await page.locator('.experiment-comparison>summary').click();
    for(const box of await page.locator('[data-compare-run]').all())await box.check();
    await page.locator('[data-compare-y]').selectOption('velocity');await page.locator('[data-compare-show]').click();
    assert.equal(await page.locator('[data-compare-chart] .graph-comparison-line').count(),1);
    assert.match(await page.locator('[data-compare-values]').textContent(),/không xác định/);
    assert.equal(await page.locator('[data-compare-seek]').isDisabled(),true,'different setup must not seek');
    const compareCsv=await download('[data-compare-csv]','studio-compare.csv');
    assert.equal(compareCsv.trim().split('\r\n').length,5);assert.ok(compareCsv.includes('velocity (m/s)'));
    const curve=page.locator('[data-compare-chart] .graph-line');const initialPath=await curve.getAttribute('d');
    await page.locator('[data-compare-chart] [data-graph-action="zoom-in"]').click();
    assert.notEqual(await curve.getAttribute('d'),initialPath);
    const zoomedPath=await curve.getAttribute('d');
    await page.locator('[data-compare-chart] [data-graph-action="pan-right"]').click();
    assert.notEqual(await curve.getAttribute('d'),zoomedPath);
    await page.locator('#force').fill('20');await page.locator('[data-compare-x]').fill('0');
    await page.locator('[data-compare-seek]').click();assert.equal(await page.locator('#scrubber').inputValue(),'0');
    await page.locator('.experiment-runs>summary').click();
    page.once('dialog',dialog=>dialog.accept('Đối chứng đã đổi tên'));await page.locator(`[data-run-rename="${id}"]`).click();
    assert.equal((await snapshot()).runs.find(run=>run.id===id).name,'Đối chứng đã đổi tên');
    await page.locator(`[data-run-view="${id}"]`).click();
    assert.equal(await page.locator('[data-run-preview] tbody tr').count(),2);
    page.once('dialog',dialog=>dialog.dismiss());await page.locator(`[data-run-delete="${id}"]`).click();
    assert.equal((await snapshot()).runs.length,2);
    await page.locator(`[data-run-edit="${id}"]`).click();
    await page.locator('[data-notebook-field="conclusion"]').fill('Đã xem lại bằng chứng sau khi reload.');
    await page.locator('[data-run-save]').click();
    assert.equal((await snapshot()).runs.find(run=>run.id===id).notebook.conclusion,'Đã xem lại bằng chứng sau khi reload.');
    const backup=await download('[data-run-backup]','studio-backup.json');
    page.once('dialog',dialog=>dialog.accept());await page.locator(`[data-run-delete="${id}"]`).click();
    assert.equal((await snapshot()).runs.length,1);
    await page.locator('[data-run-file]').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(backup)});
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('physicslab.experiments.v1')).runs.length===2);
    const before=await snapshot();
    await page.locator('[data-run-file]').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{bad')});
    await page.waitForFunction(()=>document.querySelector('[data-measure-status]').textContent.includes('Không thể nhập'));
    assert.deepEqual(await snapshot(),before);
    await page.setViewportSize({width:320,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.locator('#simulation-measurements').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'studio-2-2-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
  } finally { await context.close(); }
};
